// pnpm db:seed            upsert seed data into DATABASE_URL (idempotent)
// pnpm db:seed --reset    truncate all app tables first
// Env already set in the shell (e.g. DATABASE_URL from the test harness) wins over .env.local.
import { writeFile } from "node:fs/promises";
import { config } from "dotenv";

config({ path: ".env.local", quiet: true });

async function main() {
  const reset = process.argv.includes("--reset");
  const { db, pool } = await import("@/db");
  const { seed } = await import("@/db/seed");
  const { SEED_USERS } = await import("@/db/seed-users");
  const dbName = new URL(process.env.DATABASE_URL ?? "postgres://x/unknown").pathname.slice(1);
  try {
    const result = await seed(db, { reset });
    console.log(
      `Seeded ${dbName}${reset ? " (after reset)" : ""}: ${result.branches} branches, ${result.categories} categories, ` +
        `${result.vehicles} vehicles, ${result.extras} extras, ${result.pricingRules} pricing rules, ` +
        `${result.reservations} new sample reservations.`,
    );
    const { admin, customer } = SEED_USERS;
    await writeFile(
      "seed-users.local.md",
      [
        "# Seeded test logins (local only, gitignored; do not commit or share)",
        "",
        `Generated by \`pnpm db:seed\` for database \`${dbName}\` at ${new Date().toISOString()}.`,
        "Override with SEED_ADMIN_EMAIL / SEED_ADMIN_PASSWORD / SEED_CUSTOMER_EMAIL / SEED_CUSTOMER_PASSWORD.",
        "",
        "| Role | Email | Password |",
        "|---|---|---|",
        `| Admin | ${admin.email} | ${admin.password} |`,
        `| Customer | ${customer.email} | ${customer.password} |`,
        "",
      ].join("\n"),
    );
    console.log("Test logins written to seed-users.local.md (gitignored).");
  } finally {
    await pool.end();
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
